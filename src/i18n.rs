use serde::{Deserialize, Serialize};
use std::sync::Mutex;

#[derive(Debug, Clone, Copy, Default, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "lowercase")]
pub enum Language {
    #[default]
    En,
    Zh,
}

impl Language {
    pub fn label(&self) -> &'static str {
        match self {
            Self::En => "English",
            Self::Zh => "简体中文",
        }
    }

    pub fn all() -> &'static [Language] {
        &[Self::En, Self::Zh]
    }
}

static LANG: Mutex<Option<Language>> = Mutex::new(None);

pub fn init(lang: Language) {
    let mut guard = LANG.lock().unwrap();
    *guard = Some(lang);
}

pub fn set(lang: Language) {
    let mut guard = LANG.lock().unwrap();
    *guard = Some(lang);
}

pub fn get() -> Language {
    let guard = LANG.lock().unwrap();
    guard.unwrap_or_default()
}

pub fn tr(key: &str) -> String {
    let lang = get();
    translate(lang, key)
}

/// Translate a key to the current language.
/// Returns the English string as fallback if no translation found.
pub fn translate(lang: Language, key: &str) -> String {
    match lang {
        Language::En => en(key).map(|s| s.to_string()).unwrap_or_else(|| key.to_string()),
        Language::Zh => zh(key).unwrap_or_else(|| en(key).map(|s| s.to_string()).unwrap_or_else(|| key.to_string())),
    }
}

/// Format a translated pattern with runtime arguments.
pub fn tr_format(key: &str, args: &[&dyn std::fmt::Display]) -> String {
    let lang = get();
    let pattern = translate(lang, key);
    format_with(&pattern, args)
}

/// Format a runtime string pattern with display arguments.
fn format_with(pattern: &str, args: &[&dyn std::fmt::Display]) -> String {
    let mut result = String::with_capacity(pattern.len());
    let mut chars = pattern.chars().peekable();
    let mut arg_idx = 0;

    while let Some(ch) = chars.next() {
        if ch == '{' {
            if chars.peek() == Some(&'{') {
                chars.next();
                result.push('{');
                continue;
            }
            // Parse format spec until '}'
            let mut spec = String::new();
            let mut closed = false;
            for c in chars.by_ref() {
                if c == '}' {
                    closed = true;
                    break;
                }
                spec.push(c);
            }
            if closed {
                if arg_idx < args.len() {
                    let arg = args[arg_idx];
                    arg_idx += 1;
                    if spec.is_empty() {
                        use std::fmt::Write;
                        let _ = write!(result, "{}", arg);
                    } else if spec == ":?" {
                        // Debug - we can't do this with Display, just use Display
                        use std::fmt::Write;
                        let _ = write!(result, "{}", arg);
                    } else if let Some(rest) = spec.strip_prefix(':') {
                        if let Some(precision) = rest.strip_suffix("f") {
                            if let Ok(p) = precision.trim().parse::<usize>() {
                                use std::fmt::Write;
                                let _ = write!(result, "{:.1$}", arg, p);
                            } else {
                                use std::fmt::Write;
                                let _ = write!(result, "{}", arg);
                            }
                        } else {
                            use std::fmt::Write;
                            let _ = write!(result, "{}", arg);
                        }
                    } else {
                        use std::fmt::Write;
                        let _ = write!(result, "{}", arg);
                    }
                } else {
                    result.push('{');
                    result.push_str(&spec);
                    result.push('}');
                }
            } else {
                result.push('{');
                result.push_str(&spec);
            }
        } else if ch == '}' && chars.peek() == Some(&'}') {
            chars.next();
            result.push('}');
        } else {
            result.push(ch);
        }
    }
    result
}

// ── Convenience macro ─────────────────────────────────────────────────────────

#[macro_export]
macro_rules! tr {
    ($key:expr) => {
        $crate::i18n::tr($key)
    };
    ($key:expr, $a1:expr) => {
        $crate::i18n::tr_format($key, &[&$a1])
    };
    ($key:expr, $a1:expr, $a2:expr) => {
        $crate::i18n::tr_format($key, &[&$a1, &$a2])
    };
    ($key:expr, $a1:expr, $a2:expr, $a3:expr) => {
        $crate::i18n::tr_format($key, &[&$a1, &$a2, &$a3])
    };
    ($key:expr, $a1:expr, $a2:expr, $a3:expr, $a4:expr) => {
        $crate::i18n::tr_format($key, &[&$a1, &$a2, &$a3, &$a4])
    };
    ($key:expr, $a1:expr, $a2:expr, $a3:expr, $a4:expr, $a5:expr) => {
        $crate::i18n::tr_format($key, &[&$a1, &$a2, &$a3, &$a4, &$a5])
    };
}

